from database import init_db, get_connection, ph, placeholder, USE_POSTGRES, get_all_topics


def insert_topic(conn, title: str, emoji: str, sort_order: int) -> int:
    """Додає тему і повертає її id (для обох типів БД)"""
    if USE_POSTGRES:
        cur = conn.cursor()
        cur.execute(
            f"INSERT INTO topics (title, emoji, sort_order) VALUES ({placeholder(3)}) RETURNING id",
            (title, emoji, sort_order),
        )
        topic_id = cur.fetchone()["id"]
        conn.commit()
        cur.close()
    else:
        cur = conn.cursor()
        cur.execute(
            f"INSERT INTO topics (title, emoji, sort_order) VALUES ({placeholder(3)})",
            (title, emoji, sort_order),
        )
        conn.commit()
        topic_id = cur.lastrowid
    return topic_id


def insert_subtopic(conn, topic_id: int, title: str) -> int:
    if USE_POSTGRES:
        cur = conn.cursor()
        cur.execute(
            f"INSERT INTO subtopics (topic_id, title) VALUES ({placeholder(2)}) RETURNING id",
            (topic_id, title),
        )
        subtopic_id = cur.fetchone()["id"]
        conn.commit()
        cur.close()
    else:
        cur = conn.cursor()
        cur.execute(
            f"INSERT INTO subtopics (topic_id, title) VALUES ({placeholder(2)})",
            (topic_id, title),
        )
        conn.commit()
        subtopic_id = cur.lastrowid
    return subtopic_id


def insert_question(conn, topic_id: int, subtopic_id: int, question: str, answer: str, price: float = 99.00):
    if USE_POSTGRES:
        cur = conn.cursor()
        cur.execute(
            f"INSERT INTO questions (topic_id, subtopic_id, question, answer, price) VALUES ({placeholder(5)})",
            (topic_id, subtopic_id, question, answer, price),
        )
        conn.commit()
        cur.close()
    else:
        conn.execute(
            f"INSERT INTO questions (topic_id, subtopic_id, question, answer, price) VALUES ({placeholder(5)})",
            (topic_id, subtopic_id, question, answer, price),
        )
        conn.commit()


